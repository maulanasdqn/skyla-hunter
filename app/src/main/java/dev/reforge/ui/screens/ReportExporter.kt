package dev.reforge.ui.screens

import android.content.ContentValues
import android.content.Context
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/** Builds a markdown recon report from a session and saves it to Downloads/Reforge. */
object ReportExporter {

    fun build(title: String, messages: List<ChatMessage>): String {
        val now = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.US).format(Date())
        val tools = toolsUsed(messages)
        val sb = StringBuilder()
        sb.append("# Reforge — Recon Report\n\n")
        sb.append("**Session:** ${title.ifBlank { "Recon" }}  \n")
        sb.append("**Generated:** $now  \n")
        if (tools.isNotEmpty()) sb.append("**Tools used:** ${tools.joinToString(", ")}  \n")
        sb.append("\n---\n\n")

        for (m in messages) {
            when (m.kind) {
                MsgKind.USER -> sb.append("### ▸ ${m.text}\n\n")
                MsgKind.ANSWER, MsgKind.THOUGHT -> sb.append("${m.text}\n\n")
                MsgKind.COMMAND -> sb.append("```sh\n${m.text.removePrefix("$ ")}\n```\n\n")
                MsgKind.OUTPUT -> {
                    val out = if (m.text.length > 2500) m.text.take(2500) + "\n… (truncated)" else m.text
                    sb.append("```\n$out\n```\n\n")
                }
                MsgKind.ERROR -> sb.append("> ⚠ ${m.text}\n\n")
                MsgKind.RUNINFO -> {} // summarized in the header
            }
        }
        sb.append("\n---\n_Generated by Reforge._\n")
        return sb.toString()
    }

    /** Collect recon tool names from RUNINFO messages (fallback: scan commands). */
    fun toolsUsed(messages: List<ChatMessage>): List<String> {
        val fromRun = messages.lastOrNull { it.kind == MsgKind.RUNINFO }
            ?.text?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }
        if (!fromRun.isNullOrEmpty()) return fromRun.distinct()
        // fallback: first token of each command
        return messages.filter { it.kind == MsgKind.COMMAND }
            .map { it.text.removePrefix("$ ").trim().substringBefore(' ') }
            .filter { it.isNotEmpty() && it != "for" && it != "app" }
            .distinct()
    }

    /** Saves the report to Downloads/Reforge. Returns a display path, or null on failure. */
    fun save(context: Context, title: String, messages: List<ChatMessage>): String? {
        val md = build(title, messages)
        val stamp = SimpleDateFormat("yyyyMMdd-HHmm", Locale.US).format(Date())
        val name = "reforge-report-$stamp.md"
        return try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                val values = ContentValues().apply {
                    put(MediaStore.Downloads.DISPLAY_NAME, name)
                    put(MediaStore.Downloads.MIME_TYPE, "text/markdown")
                    put(MediaStore.Downloads.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS + "/Reforge")
                }
                val uri = context.contentResolver.insert(
                    MediaStore.Downloads.EXTERNAL_CONTENT_URI, values
                ) ?: return null
                context.contentResolver.openOutputStream(uri)?.use { it.write(md.toByteArray()) }
                "Download/Reforge/$name"
            } else {
                val dir = java.io.File(
                    Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS), "Reforge"
                ).apply { mkdirs() }
                java.io.File(dir, name).writeText(md)
                "Download/Reforge/$name"
            }
        } catch (e: Exception) {
            null
        }
    }
}
