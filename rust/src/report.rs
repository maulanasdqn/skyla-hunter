//! Recon-report builder, ported from Kotlin `ReportExporter.build`/`toolsUsed`.
//!
//! Pure: turns a list of chat messages into a Markdown report string, and
//! collects the recon tools a session used. The Android side keeps only the
//! parts that touch the framework — computing the timestamp (passed in here as
//! `generated`) and writing the file to Downloads.

/// Mirror of the app's `MsgKind`. Named `ReportKind` to avoid clashing with the
/// Kotlin enum of the same purpose across the FFI boundary.
#[derive(uniffi::Enum, Clone, Copy, PartialEq, Eq, Debug)]
pub enum ReportKind {
    User,
    Thought,
    Command,
    Output,
    Answer,
    Error,
    RunInfo,
}

/// One chat message: its kind and text (the app's `id` is irrelevant here).
#[derive(uniffi::Record, Clone, Debug)]
pub struct ReportMessage {
    pub kind: ReportKind,
    pub text: String,
}

/// De-duplicate while preserving first-seen order.
fn distinct(items: impl IntoIterator<Item = String>) -> Vec<String> {
    let mut seen: Vec<String> = Vec::new();
    for it in items {
        if !seen.contains(&it) {
            seen.push(it);
        }
    }
    seen
}

/// Recon tool names a session used: prefer the latest `RunInfo` message (a
/// comma-separated list); otherwise fall back to the first token of every
/// command, minus shell noise (`for`, `app`).
#[uniffi::export]
pub fn tools_used(messages: Vec<ReportMessage>) -> Vec<String> {
    if let Some(run) = messages
        .iter()
        .rev()
        .find(|m| m.kind == ReportKind::RunInfo)
    {
        let from_run: Vec<String> = run
            .text
            .split(',')
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect();
        if !from_run.is_empty() {
            return distinct(from_run);
        }
    }
    let fallback = messages
        .iter()
        .filter(|m| m.kind == ReportKind::Command)
        .map(|m| {
            m.text
                .strip_prefix("$ ")
                .unwrap_or(&m.text)
                .trim()
                .split(' ')
                .next()
                .unwrap_or("")
                .to_string()
        })
        .filter(|t| !t.is_empty() && t != "for" && t != "app");
    distinct(fallback)
}

/// Build the Markdown recon report. `generated` is a preformatted timestamp
/// (the caller owns locale/clock); `title` blank falls back to "Recon".
#[uniffi::export]
pub fn build_report(title: String, generated: String, messages: Vec<ReportMessage>) -> String {
    let tools = tools_used(messages.clone());
    let mut s = String::new();
    s.push_str("# Reforge — Recon Report\n\n");
    let t = if title.trim().is_empty() { "Recon" } else { &title };
    s.push_str(&format!("**Session:** {t}  \n"));
    s.push_str(&format!("**Generated:** {generated}  \n"));
    if !tools.is_empty() {
        s.push_str(&format!("**Tools used:** {}  \n", tools.join(", ")));
    }
    s.push_str("\n---\n\n");

    for m in &messages {
        match m.kind {
            ReportKind::User => s.push_str(&format!("### ▸ {}\n\n", m.text)),
            ReportKind::Answer | ReportKind::Thought => s.push_str(&format!("{}\n\n", m.text)),
            ReportKind::Command => {
                let cmd = m.text.strip_prefix("$ ").unwrap_or(&m.text);
                s.push_str(&format!("```sh\n{cmd}\n```\n\n"));
            }
            ReportKind::Output => {
                let out = if m.text.chars().count() > 2500 {
                    let head: String = m.text.chars().take(2500).collect();
                    format!("{head}\n… (truncated)")
                } else {
                    m.text.clone()
                };
                s.push_str(&format!("```\n{out}\n```\n\n"));
            }
            ReportKind::Error => s.push_str(&format!("> ⚠ {}\n\n", m.text)),
            ReportKind::RunInfo => {} // summarized in the header
        }
    }
    s.push_str("\n---\n_Generated by Reforge._\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    fn m(kind: ReportKind, text: &str) -> ReportMessage {
        ReportMessage { kind, text: text.into() }
    }

    #[test]
    fn tools_prefer_runinfo() {
        let msgs = vec![
            m(ReportKind::Command, "$ nmap -sV t"),
            m(ReportKind::RunInfo, "nmap, nikto, nmap"),
        ];
        assert_eq!(tools_used(msgs), vec!["nmap", "nikto"]);
    }

    #[test]
    fn tools_fallback_to_commands() {
        let msgs = vec![
            m(ReportKind::Command, "$ nmap -sV t"),
            m(ReportKind::Command, "for i in x"),
            m(ReportKind::Command, "whatweb t"),
            m(ReportKind::Command, "nmap again"),
        ];
        assert_eq!(tools_used(msgs), vec!["nmap", "whatweb"]);
    }

    #[test]
    fn report_has_header_and_blocks() {
        let msgs = vec![
            m(ReportKind::User, "scan it"),
            m(ReportKind::Command, "$ nmap t"),
            m(ReportKind::Output, "80/tcp open"),
            m(ReportKind::RunInfo, "nmap"),
        ];
        let r = build_report("".into(), "2026-01-01 00:00".into(), msgs);
        assert!(r.contains("**Session:** Recon"));
        assert!(r.contains("**Generated:** 2026-01-01 00:00"));
        assert!(r.contains("**Tools used:** nmap"));
        assert!(r.contains("### ▸ scan it"));
        assert!(r.contains("```sh\nnmap t\n```"));
        assert!(r.contains("```\n80/tcp open\n```"));
    }

    #[test]
    fn output_truncates_over_2500() {
        let big = "a".repeat(3000);
        let r = build_report("t".into(), "g".into(), vec![m(ReportKind::Output, &big)]);
        assert!(r.contains("… (truncated)"));
        assert!(!r.contains(&"a".repeat(2600)));
    }
}
